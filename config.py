"""
=====================================================
Minesweeper - Configuration
=====================================================

게임의 기본 설정과 규칙을 관리하는 파일입니다.

구성:
- 게임판 크기
- 지뢰 개수
- 첫 클릭 안전 여부
- Cash Out 조건
- 보상 배율
=====================================================
"""


# =====================================================
# 게임 기본 설정
# =====================================================

# 게임판 크기
ROWS = 5
COLS = 5

# 전체 칸 수
TOTAL_CELLS = ROWS * COLS


# =====================================================
# 지뢰 / 안전 칸 설정
# =====================================================

# 지뢰 개수
BOMB_COUNT = 5

# 안전한 칸 개수
SAFE_CELL_COUNT = TOTAL_CELLS - BOMB_COUNT


# =====================================================
# 게임 규칙
# =====================================================

# 첫 번째 클릭한 칸에는 지뢰가 나오지 않음
FIRST_CLICK_SAFE = True

# Cash Out을 할 수 있는 최소 안전 칸 개수
MIN_CASHOUT = 5


# =====================================================
# 보상 배율
# =====================================================

"""
안전한 칸을 찾을수록 배율이 증가합니다.

예:
5칸 성공 → 3.0배
6칸 성공 → 4.0배
7칸 성공 → 5.5배
...
"""

PAYOUTS = {

    5: 3.0,

    6: 4.0,

    7: 5.5,

    8: 7.5,

    9: 10.5,

    10: 15.0,

    11: 20.0,

    12: 30.0,
}


# =====================================================
# 베팅 설정
# =====================================================

# 베팅 금액 최소 단위
BET_UNIT = 100

# 최소 베팅 금액
MIN_BET = 100


# =====================================================
# 초기 잔액 설정
# =====================================================

# 사용자가 게임 시작 시 입력할 수 있는 최소 잔액
MIN_BALANCE = 100

# 잔액 입력 단위
BALANCE_UNIT = 100


# =====================================================
# 화면 설정
# =====================================================

TITLE = "💣 Minesweeper"

PAGE_TITLE = "Minesweeper"

PAGE_ICON = "💣"


# =====================================================
# 게임 메시지
# =====================================================

GAME_START_TEXT = "게임을 시작합니다."

GEM_TEXT = "안전한 칸입니다!"

BOMB_TEXT = "지뢰를 발견했습니다!"

CASHOUT_TEXT = "Cash Out 성공!"

GAME_OVER_TEXT = "게임이 종료되었습니다."

CONTINUE_TEXT = "다음 게임을 진행하시겠습니까?"

FINAL_TEXT = "게임을 종료합니다."


# =====================================================
# 설정 검증
# =====================================================

# 지뢰가 최소 1개는 있어야 함
assert BOMB_COUNT > 0, \
    "지뢰 개수는 1개 이상이어야 합니다."


# 지뢰가 전체 칸보다 많을 수 없음
assert BOMB_COUNT < TOTAL_CELLS, \
    "지뢰 개수가 게임판 전체 칸보다 많거나 같을 수 없습니다."


# Cash Out 최소 조건이 보상표에 존재해야 함
assert MIN_CASHOUT in PAYOUTS, \
    "MIN_CASHOUT 값이 PAYOUTS에 존재하지 않습니다."


# 베팅 단위 검증
assert BET_UNIT > 0, \
    "BET_UNIT은 0보다 커야 합니다."


# 최소 베팅 검증
assert MIN_BET >= BET_UNIT, \
    "MIN_BET은 BET_UNIT보다 작을 수 없습니다."


# 잔액 단위 검증
assert BALANCE_UNIT > 0, \
    "BALANCE_UNIT은 0보다 커야 합니다."
